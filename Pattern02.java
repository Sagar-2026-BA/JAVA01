public class Pattern02{
    public static void main(String args[]){
        for(int i=0;i<=4;i++){
            if(i==0 || i==4){
                System.out.println("* * * * *");
                    }
            else if(i==1){
                System.out.println("* *     *");
                    }
            else if(i==2){
                System.out.println("*   *   *");
                    }
            else if(i==3){
                System.out.println("*     * *");
                    }
            }
        }
    }